// Builds the talk pane into src/console/web/app/ (chat.js, chat.css): fixed names, listed in src/console/web.ts.
// The output is committed and marked generated; check.sh rebuilds it and compares. HH_UI_OUT builds elsewhere (check.sh).
import { defineConfig } from "vite";
import type { Plugin } from "vite";
import react from "@vitejs/plugin-react";

const BANNER = "/* generated by console-ui (vite build): do not edit; see console-ui/BUILD.md */";

/** the banner on chat.js, so a reader of src/console/web/app/ knows not to edit it (chat.css carries it as a kept comment in src/chat.css) */
const banner = (): Plugin => ({
  name: "hh-generated-banner",
  generateBundle(_, bundle) {
    for (const f of Object.values(bundle)) {
      if (f.type === "chunk") f.code = `${BANNER}\n${f.code}`;
    }
  },
});

export default defineConfig({
  plugins: [react(), banner()],
  base: "/web/app/",
  build: {
    outDir: process.env.HH_UI_OUT ?? "../src/console/web/app",
    emptyOutDir: true,
    cssCodeSplit: false,
    modulePreload: false,
    sourcemap: false,
    chunkSizeWarningLimit: 800,
    rolldownOptions: {
      input: "src/main.tsx",
      output: { entryFileNames: "chat.js", assetFileNames: "chat[extname]", codeSplitting: false },
    },
  },
});
