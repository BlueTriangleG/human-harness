def build_fitting(memory_mode: str = "pointer", limit: int = MAX_CHARS) -> tuple[str, list[str], tuple | None, int]:
    """从不缩开始，一档一档加，直到不超过 limit；全缩了还超就按整行截（最后手段）。"""
    M = _midterm_module()
    threads = None
    if M is not None:
        try:
            threads = M.load_threads()
        except Exception as e:
            print(f"load_threads failed: {e}", file=sys.stderr)
    n = len(shrink_steps())
    content, notes, used = "", [], None
    for level in range(n + 1):
        content, notes, used = build(level, memory_mode, threads)
        if len(content) <= limit:
            return content, notes, used, level
    print(f"snapshot still {len(content)} chars after shrinking everything; truncating", file=sys.stderr)
    out, size = [], 0
    tail = say("snapTruncated")
    for l in content.splitlines():
        if size + len(l) + 1 > limit - len(tail):
            break
        out.append(l)
        size += len(l) + 1
    return "\n".join(out) + tail, notes + [say("snapTruncatedNote")], used, n + 1


