MONEY_RE = re.compile(r"(\d+\s*(刀|块|元|澳币|美元|AUD|USD))|\$\s*\d|付了|交了|已付|已交")
DATE_RE = re.compile(r"(20\d{2})-(\d{2})-(\d{2})|(?<!\d)(\d{1,2})-(\d{2})(?!\d)")


def _dates(text: str, today: datetime.date) -> list[datetime.date]:
    out = []
    for m in DATE_RE.finditer(text):
        try:
            if m.group(1):
                out.append(datetime.date(int(m.group(1)), int(m.group(2)), int(m.group(3))))
            else:
                d = datetime.date(today.year, int(m.group(4)), int(m.group(5)))
                out.append(d if d >= today - datetime.timedelta(days=180) else d.replace(year=today.year + 1))
        except ValueError:
            pass
    return out


