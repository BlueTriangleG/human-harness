PRI_RE = re.compile(r"优先级[：:]\s*(T[0-3])")


def _pri(item: str) -> str:
    """待办账本就是她的记事本（10-31）：优先级 T0–T3，没写的当 T2"""
    m = PRI_RE.search(item)
