def _clip(l: str) -> str:
    return l if len(l) <= MAX_LOOP_CHARS else l[:MAX_LOOP_CHARS] + "…"


def _loop_items() -> list[str]:
    """进行中的待办（整行，没截断），按优先级排，同一优先级保持原顺序。"""
    p = WS / "memory" / "open-loops.md"
    if not p.exists():
        return []
    body = section(p.read_text(encoding="utf-8"), "|".join(map(re.escape, form.every("loopsOpen"))))
    items = []
    for l in body.splitlines():
        if l.startswith("- [ ]"):
            items.append(re.sub(r"<!--.*?-->", "", l).strip())
    return sorted(items, key=_pri)


def open_loops(hide_stale_days: int | None = None) -> tuple[str, int]:
    """进行中的待办。hide_stale_days：最新的日期已经过去这么多天、又没有将来日期的条目先不放（快照超长时），T0、T1 照放。"""
    items = _loop_items()
    if not items and not (WS / "memory" / "open-loops.md").exists():
        return say("snapEmpty"), 0
    hidden = 0
    if hide_stale_days:
        today = her_today()
        keep = []
        for it in items:
            ds = _dates(it, today)
            past = [d for d in ds if d <= today]
            future = [d for d in ds if d > today]
            if past and not future and (today - max(past)).days >= hide_stale_days and _pri(it) not in ("T0", "T1"):
                hidden += 1
                continue
            keep.append(it)
        items = keep
    text = "\n".join(_clip(it) for it in items) or say("snapNone")
    if hidden:
        text += say("snapLoopsHidden", hidden=hidden, hide_stale_days=hide_stale_days)
    return text, hidden


