def card_sections(key: str) -> list[tuple[str, str]]:
    """读 ledger/people/<key>.md，按「## 」切成 [(段名, 正文)]（卡头的「# 名字」和说明不要）；没有文件返回 []。"""
    if not key or "/" in key or key.startswith("."):
        return []
    p = PEOPLE_DIR / f"{key}.md"
    if not p.is_file():
        return []
    out, cur, buf = [], None, []
    for line in p.read_text(encoding="utf-8").splitlines():
        if line.startswith("## "):
            if cur is not None:
                out.append((cur, "\n".join(buf).strip()))
            cur, buf = line[3:].strip(), []
        elif cur is not None:
            buf.append(line.rstrip())
    if cur is not None:
        out.append((cur, "\n".join(buf).strip()))
    return out


def render_sections(secs: list[tuple[str, str]]) -> str:
    """卡的段贴进快照：标题降成 ###，空段不放。"""
    return "\n\n".join(f"### {name}\n{body}" for name, body in secs if body)


def section(text: str, heading_re: str) -> str:
    """Return the body of the first heading (## or **bold**) matching heading_re."""
    lines = text.splitlines()
    out, inside = [], False
    for line in lines:
        is_heading = line.startswith("#") or re.match(r"^\*\*[^*]+\*\*", line)
        if is_heading and re.search(heading_re, line):
            inside = True
            # bold-style heading with inline content: "**现在的状态（…）**：xxx"
            rest = re.sub(r"^\*\*[^*]+\*\*[:：]?\s*", "", line) if line.startswith("**") else ""
            if rest:
                out.append(rest)
            continue
        if inside and line.startswith("## "):
            break
        if inside and line.strip():
            out.append(line.rstrip())
    return "\n".join(out).strip()


def her_today() -> datetime.date:
    return (datetime.datetime.now() - datetime.timedelta(hours=DAY_START)).date()


def timeline(days: int = 2) -> str:
    """时间轴里最近 days 天（她的一天，凌晨 4 点换）的条目；按时间，不按条数。"""
    p = WS / "memory" / "timeline.md"
    if not p.exists():
        return say("snapEmpty")
    today = her_today()
    since = today - datetime.timedelta(days=days - 1)
    items = []
    for l in p.read_text(encoding="utf-8").splitlines():
        m = re.match(r"^- (\d{4}-\d{2}-\d{2})(?:[ T](\d{1,2}):\d{2})?", l)
        if not m:
            continue
        d = datetime.date.fromisoformat(m.group(1))
        if m.group(2) is not None and int(m.group(2)) < DAY_START:
            d -= datetime.timedelta(days=1)
        if d >= since:
            items.append(l.rstrip())
    return "\n".join(items) or say("snapNoNewEntries")


def timeline_today() -> str:
    """时间轴里今天（她的一天，凌晨 4 点换）的条目，记忆的写法（主人 10-29）：不写日期；时间精确到半小时
    （往下取整到 :00 / :30），和上一个写出来的时间隔不到半小时的不写时间。"""
    p = WS / "memory" / "timeline.md"
    if not p.exists():
        return say("snapNothingToday")
    today = her_today()
    items, last = [], None
    for l in p.read_text(encoding="utf-8").splitlines():
        m = re.match(r"^- (\d{4}-\d{2}-\d{2})(?:[ T](\d{1,2})[:：](\d{2}|[0-5][xX]|[xX]{1,2}))?\s*(.*)$", l)
        if not m:
            continue
        d = datetime.date.fromisoformat(m.group(1))
        h = int(m.group(2)) if m.group(2) is not None else None
        if h is not None and h < DAY_START:
            d -= datetime.timedelta(days=1)
        if d != today:
            continue
        rest = m.group(4).rstrip()
        if h is None:
            items.append((None, rest))
            continue
        mm = m.group(3) or "00"
        mins = h * 60 + (int(mm) if mm.isdigit() else int(mm[0]) * 10 if mm[0].isdigit() else 0)
        items.append(((mins + (24 * 60 if h < DAY_START else 0)) // 30 * 30, rest))   # 凌晨的排在当天最后
    # 对账补记的会晚加在后面：按时间排（没时间的跟在前一条后面，稳定排序）
    keyed, k = [], -1
    for t, rest in items:
        k = t if t is not None else k
        keyed.append((k, t, rest))
    out = []
    for _, t, rest in sorted(keyed, key=lambda x: x[0]):
        if t is None or (last is not None and t - last < 30):
            out.append(f"- {rest}")
        else:
            out.append(f"- {t // 60 % 24:02d}:{t % 60:02d} {rest}")
            last = t
    return "\n".join(out) or say("snapNothingToday")


